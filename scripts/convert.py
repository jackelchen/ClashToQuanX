#!/usr/bin/env python3
"""
Convert Clash rule lists (filter/*.list) to a Quantumult X filter list.

Source : <repo>/filter/*.list
Output : <repo>/output/quanx.list
Config : <repo>/scripts/policy_map.json
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLASH_DIR = ROOT / "filter"
OUTPUT_FILE = ROOT / "output" / "quanx.list"
MAP_FILE = Path(__file__).resolve().parent / "policy_map.json"

# Clash rule type -> Quantumult X rule type
# None = unsupported, line will be emitted as a comment
TYPE_MAP = {
    "DOMAIN": "HOST",
    "DOMAIN-SUFFIX": "HOST-SUFFIX",
    "DOMAIN-KEYWORD": "HOST-KEYWORD",
    "DOMAIN-WILDCARD": None,
    "IP-CIDR": "IP-CIDR",
    "IP-CIDR6": "IP6-CIDR",
    "IP6-CIDR": "IP6-CIDR",
    "IP-ASN": "IP-ASN",
    "GEOIP": "GEOIP",
    "USER-AGENT": "USER-AGENT",
    "SRC-IP-CIDR": "SRC-IP-CIDR",
    "SRC-IP-CIDR6": "SRC-IP6-CIDR",
    "DST-PORT": "DST-PORT",
    "SRC-PORT": "SRC-PORT",
    "PROCESS-NAME": None,
    "PROCESS-PATH": None,
    "RULE-SET": None,
    "URL-REGEX": "URL-REGEX",
    "MATCH": "FINAL",
    "FINAL": "FINAL",
}


def load_config():
    with MAP_FILE.open("r", encoding="utf-8") as f:
        cfg = json.load(f)
    return {
        "policy_map": cfg.get("policy_map", {}),
        "default_policy": cfg.get("default_policy", "自动选择"),
        "final_policy": cfg.get("final_policy", "direct"),
        "emit_final": cfg.get("emit_final", True),
        "skip_files": set(cfg.get("skip_files", [])),
    }


def convert_line(raw, cfg):
    """Return converted line, or None to drop, or a '# ...' comment."""
    line = raw.strip()
    if not line:
        return None
    if line.startswith("#"):
        return line
    # tolerate YAML-style '- DOMAIN,...'
    if line.startswith("- "):
        line = line[2:].strip()

    parts = [p.strip() for p in line.split(",")]
    rule_type = parts[0].upper()

    if rule_type in ("MATCH", "FINAL"):
        if not cfg["emit_final"]:
            return None
        return f"FINAL,{cfg['final_policy']}"

    if rule_type not in TYPE_MAP:
        return f"# SKIP unknown type: {line}"
    qx_type = TYPE_MAP[rule_type]
    if qx_type is None:
        return f"# SKIP unsupported type: {line}"
    if len(parts) < 3:
        return f"# SKIP missing fields: {line}"

    value = parts[1]
    policy = parts[2]
    extra = parts[3:]

    qx_policy = cfg["policy_map"].get(policy, cfg["default_policy"])

    out = f"{qx_type},{value},{qx_policy}"
    if extra:
        out += "," + ",".join(extra)
    return out


def convert_file(path, cfg):
    with path.open("r", encoding="utf-8-sig") as f:
        for raw in f:
            yield convert_line(raw, cfg)


def main():
    if not CLASH_DIR.is_dir():
        print(f"error: {CLASH_DIR} not found", file=sys.stderr)
        sys.exit(1)

    cfg = load_config()
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)

    files = sorted(
        p for p in CLASH_DIR.glob("*.list") if p.name not in cfg["skip_files"]
    )
    if not files:
        print(f"error: no *.list files in {CLASH_DIR}", file=sys.stderr)
        sys.exit(1)

    out = [
        "# Auto-generated by scripts/convert.py. DO NOT EDIT.",
        "# Source: filter/*.list",
        "",
    ]
    seen = set()
    dup = 0
    skip = 0

    for path in files:
        out.append(f"# ===== {path.name} =====")
        for line in convert_file(path, cfg):
            if line is None:
                continue
            if line.startswith("#"):
                out.append(line)
                if line.startswith("# SKIP"):
                    skip += 1
                continue
            if line in seen:
                dup += 1
                continue
            seen.add(line)
            out.append(line)
        out.append("")

    # 追加 FINAL 兜底:始终位于全部规则末尾,避免新增文件打乱顺序
    if cfg["emit_final"]:
        final = f"FINAL,{cfg['final_policy']}"
        if final not in seen:
            out.append("# ===== FINAL =====")
            out.append(final)
            seen.add(final)

    OUTPUT_FILE.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(
        f"wrote {OUTPUT_FILE} | files={len(files)} "
        f"rules={len(seen)} dup_dropped={dup} skipped={skip}"
    )


if __name__ == "__main__":
    main()