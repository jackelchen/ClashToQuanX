#!/usr/bin/env python3
"""
Convert Clash rule lists (filter/*.list) to a Quantumult X filter list.
Output : <repo>/output/quanx.list
Config : <repo>/scripts/quanx/policy_map.json

同时维护 policy_map.json：新增非 0 开头的 list 时，自动把缺失的策略名补成默认映射。
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
CLASH_DIR = ROOT / "filter"
OUTPUT_FILE = ROOT / "output" / "quanx.list"
MAP_FILE = Path(__file__).resolve().parent / "policy_map.json"

# Clash rule type -> Quantumult X rule type
# None = unsupported, line will be emitted as a comment
TYPE_MAP = {
    "DOMAIN": "HOST",
    "DOMAIN-SUFFIX": "HOST-SUFFIX",
    "DOMAIN-KEYWORD": "HOST-KEYWORD",
    "DOMAIN-WILDCARD": None,
    "IP-CIDR": "IP-CIDR",
    "IP-CIDR6": "IP6-CIDR",
    "IP6-CIDR": "IP6-CIDR",
    "IP-ASN": "IP-ASN",
    "GEOIP": "GEOIP",
    "USER-AGENT": "USER-AGENT",
    "SRC-IP-CIDR": "SRC-IP-CIDR",
    "SRC-IP-CIDR6": "SRC-IP6-CIDR",
    "DST-PORT": "DST-PORT",
    "SRC-PORT": "SRC-PORT",
    "PROCESS-NAME": None,
    "PROCESS-PATH": None,
    "RULE-SET": None,
    "URL-REGEX": "URL-REGEX",
    "MATCH": "FINAL",
    "FINAL": "FINAL",
}


def load_config(data):
    """从已读取的配置 dict 提取转换所需字段。"""
    return {
        "policy_map": data.get("policy_map", {}),
        "default_policy": data.get("default_policy", "自动选择"),
        "final_policy": data.get("final_policy", "direct"),
        "emit_final": data.get("emit_final", True),
    }


def convert_line(raw, cfg):
    """Return converted line, or None to drop, or a '# ...' comment."""
    line = raw.strip()
    if not line:
        return None
    if line.startswith("#"):
        return line
    # tolerate YAML-style '- DOMAIN,...'
    if line.startswith("- "):
        line = line[2:].strip()

    parts = [p.strip() for p in line.split(",")]
    rule_type = parts[0].upper()

    if rule_type in ("MATCH", "FINAL"):
        if not cfg["emit_final"]:
            return None
        return f"FINAL,{cfg['final_policy']}"

    if rule_type not in TYPE_MAP:
        return f"# SKIP unknown type: {line}"
    qx_type = TYPE_MAP[rule_type]
    if qx_type is None:
        return f"# SKIP unsupported type: {line}"
    if len(parts) < 3:
        return f"# SKIP missing fields: {line}"

    value = parts[1]
    policy = parts[2]
    extra = parts[3:]

    qx_policy = cfg["policy_map"].get(policy, cfg["default_policy"])

    out = f"{qx_type},{value},{qx_policy}"
    if extra:
        out += "," + ",".join(extra)
    return out


def convert_file(path, cfg):
    with path.open("r", encoding="utf-8-sig") as f:
        for raw in f:
            yield convert_line(raw, cfg)


def update_policy_map(data, stems: list[str]) -> None:
    """把缺失的策略名补进 policy_map：手动项保持原顺序，非 0 条目按字母序、缺省用 default_policy。"""
    p_map = data.setdefault("policy_map", {})
    default = data.get("default_policy", "自动选择")

    auto = set(stems)
    # 手动项：当前存在但不在自动集合里的 key，保留原顺序与值
    manual_keys = [k for k in p_map if k not in auto]

    out = {}
    for k in manual_keys:
        out[k] = p_map[k]
    for s in stems:
        out[s] = p_map.get(s, default)

    if out != p_map:
        data["policy_map"] = out
        MAP_FILE.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )


def main():
    if not CLASH_DIR.is_dir():
        print(f"error: {CLASH_DIR} not found", file=sys.stderr)
        sys.exit(1)

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)

    with MAP_FILE.open("r", encoding="utf-8") as f:
        data = json.load(f)

    skip = set(data.get("skip_files", []))
    files = sorted(
        p for p in CLASH_DIR.glob("*.list") if p.name not in skip
    )
    if not files:
        print(f"error: no *.list files in {CLASH_DIR}", file=sys.stderr)
        sys.exit(1)

    stems = sorted(p.stem for p in files if not p.stem.startswith("0"))
    update_policy_map(data, stems)
    cfg = load_config(data)

    out = [
        "# Auto-generated by scripts/gen_quanx.py. DO NOT EDIT.",
        "# Source: filter/*.list",
        "",
    ]
    seen = set()
    dup = 0
    skip = 0

    for path in files:
        out.append(f"# ===== {path.name} =====")
        for line in convert_file(path, cfg):
            if line is None:
                continue
            if line.startswith("#"):
                out.append(line)
                if line.startswith("# SKIP"):
                    skip += 1
                continue
            if line in seen:
                dup += 1
                continue
            seen.add(line)
            out.append(line)
        out.append("")

    # 追加 FINAL 兜底:始终位于全部规则末尾,避免新增文件打乱顺序
    if cfg["emit_final"]:
        final = f"FINAL,{cfg['final_policy']}"
        if final not in seen:
            out.append("# ===== FINAL =====")
            out.append(final)
            seen.add(final)

    OUTPUT_FILE.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(
        f"wrote {OUTPUT_FILE} | files={len(files)} "
        f"rules={len(seen)} dup_dropped={dup} skipped={skip}"
    )


if __name__ == "__main__":
    main()